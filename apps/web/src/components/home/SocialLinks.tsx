function iconFor(platform: string): React.ReactNode {
  const key = platform.trim().toLowerCase();
  if (key.includes("git")) return ICONS.github;
  if (key.includes("linked")) return ICONS.linkedin;
  if (key.includes("youtube") || key === "yt") return ICONS.youtube;
  if (key.includes("insta")) return ICONS.instagram;
  if (key.includes("facebook") || key === "fb") return ICONS.facebook;
  if (key.includes("tiktok")) return ICONS.tiktok;
  if (key === "x" || key.includes("twitter")) return ICONS.twitter;
  if (key.includes("mail")) return ICONS.email;
  return ICONS.website;
}

interface SocialLinksProps {
  links: { platform: string; url: string }[];
}

/**
 * Enlaces sociales del perfil, dibujados como marcas geométricas simples (no
 * emoji ni una librería de íconos) para mantener la gramática de "panel de
 * instrumentos" del resto del sistema.
 */
export function SocialLinks({ links }: SocialLinksProps) {
  if (links.length === 0) return null;

  return (
    <div className="flex flex-wrap gap-2">
      {links.map((link) => (
        <a
          key={link.platform + link.url}
          href={link.url}
          target="_blank"
          rel="noreferrer"
          className="group flex items-center gap-2 rounded-sm border border-line px-3 py-1.5 font-mono text-xs uppercase tracking-wide text-ink-muted transition-colors hover:border-signal hover:text-signal"
        >
          <svg
            viewBox="0 0 16 16"
            width="13"
            height="13"
            fill="currentColor"
            className="text-ink-faint transition-colors group-hover:text-signal"
            aria-hidden
          >
            {iconFor(link.platform)}
          </svg>
          {link.platform}
        </a>
      ))}
    </div>
  );
}
